/* ============ Интерактив ============ */
function initAccordion() {
  document.querySelectorAll(".glass-card").forEach(card => {
    const head = card.querySelector(".card-head");
    const body = card.querySelector(".card-body");
    head.addEventListener("click", () => {
      const isOpen = card.classList.toggle("open");
      head.setAttribute("aria-expanded", String(isOpen));
      body.style.maxHeight = isOpen ? body.scrollHeight + "px" : "0px";
      // после анимации снимаем фиксированную высоту, чтобы контент мог меняться
      if (isOpen) {
        body.addEventListener("transitionend", function onEnd() {
          if (card.classList.contains("open")) body.style.maxHeight = "none";
          body.removeEventListener("transitionend", onEnd);
        });
      }
    });
  });

  document.getElementById("toggleAll").addEventListener("click", (e) => {
    const cards = [...document.querySelectorAll(".glass-card")];
    const anyClosed = cards.some(c => !c.classList.contains("open"));
    cards.forEach(card => {
      const head = card.querySelector(".card-head");
      const body = card.querySelector(".card-body");
      card.classList.toggle("open", anyClosed);
      head.setAttribute("aria-expanded", String(anyClosed));
      body.style.maxHeight = anyClosed ? "none" : "0px";
    });
    e.currentTarget.textContent = anyClosed ? "Свернуть все блоки" : "Развернуть все блоки";
  });
}

function initScrollReveal() {
  const io = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });

  document.querySelectorAll(".glass-card, .cheat-item").forEach(el => io.observe(el));
}

function initProgress() {
  const bar = document.querySelector(".progress-bar");
  const onScroll = () => {
    const h = document.documentElement;
    const scrolled = h.scrollTop / (h.scrollHeight - h.clientHeight);
    bar.style.width = (scrolled * 100).toFixed(2) + "%";
  };
  document.addEventListener("scroll", onScroll, { passive: true });
  onScroll();
}

/* Лёгкий 3D-tilt карточек под курсором (десктоп) */
function initTilt() {
  if (!window.matchMedia("(hover: hover) and (pointer: fine)").matches) return;
  document.querySelectorAll(".glass-card").forEach(card => {
    card.addEventListener("mousemove", (e) => {
      if (!card.classList.contains("visible")) return;
      const r = card.getBoundingClientRect();
      const px = (e.clientX - r.left) / r.width - 0.5;
      const py = (e.clientY - r.top) / r.height - 0.5;
      card.style.transform =
        `perspective(900px) rotateX(${(-py * 4).toFixed(2)}deg) rotateY(${(px * 5).toFixed(2)}deg) translateY(-6px)`;
    });
    card.addEventListener("mouseleave", () => {
      card.style.transform = "";
    });
  });
}

/* Параллакс blob-градиентов за курсором */
function initBlobParallax() {
  if (!window.matchMedia("(hover: hover) and (pointer: fine)").matches) return;
  const blobs = document.querySelectorAll(".blob");
  document.addEventListener("mousemove", (e) => {
    const x = (e.clientX / window.innerWidth - 0.5) * 2;
    const y = (e.clientY / window.innerHeight - 0.5) * 2;
    blobs.forEach((b, i) => {
      const depth = (i + 1) * 8;
      b.style.translate = `${x * depth}px ${y * depth}px`;
    });
  }, { passive: true });
}

document.addEventListener("DOMContentLoaded", () => {
  render();
  initAccordion();
  initScrollReveal();
  initProgress();
  initTilt();
  initBlobParallax();
});
